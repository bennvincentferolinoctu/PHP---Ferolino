-- ---------------------------------------------------------------------
-- Triggers: audit timestamps + cross-row date rule
-- ---------------------------------------------------------------------
create function set_updated_at() returns trigger language plpgsql as $$
begin
    new.updated_at := now();
    return new;
end $$;

create trigger trg_app_user_upd  before update on app_user  for each row execute function set_updated_at();
create trigger trg_farmer_upd    before update on farmer    for each row execute function set_updated_at();
create trigger trg_farm_upd      before update on farm      for each row execute function set_updated_at();
create trigger trg_crop_upd      before update on crop      for each row execute function set_updated_at();
create trigger trg_planting_upd  before update on planting  for each row execute function set_updated_at();
create trigger trg_harvest_upd   before update on harvest   for each row execute function set_updated_at();

-- A harvest cannot happen before its planting date.
create function check_harvest_date() returns trigger language plpgsql as $$
declare p date;
begin
    select planting_date into p from planting where planting_id = new.planting_id;
    if new.harvest_date < p then
        raise exception 'Harvest date (%) cannot be earlier than planting date (%)', new.harvest_date, p
            using errcode = '23514';
    end if;
    return new;
end $$;
create trigger trg_harvest_date before insert or update on harvest
    for each row execute function check_harvest_date();

-- Changing a planting date must not put existing harvests before it.
create function check_planting_dates() returns trigger language plpgsql as $$
begin
    if exists (select 1 from harvest h where h.planting_id = new.planting_id
               and h.harvest_date < new.planting_date) then
        raise exception 'Planting date (%) is later than an existing harvest date for this planting', new.planting_date
            using errcode = '23514';
    end if;
    return new;
end $$;
create trigger trg_planting_dates before update on planting
    for each row execute function check_planting_dates();

-- ---------------------------------------------------------------------
-- Security: block the public Supabase Data API (anon / authenticated keys).
-- The PHP app connects with the database role (postgres), which bypasses RLS.
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
    foreach t in array array['user_role','soil_type','irrigation_type','crop_category','season',
        'planting_status','quality_grade','harvest_remark','app_user','farmer','farm','crop','planting','harvest']
    loop
        execute format('alter table %I enable row level security', t);
    end loop;
end $$;

-- ---------------------------------------------------------------------
-- Reporting view
-- ---------------------------------------------------------------------
create or replace view v_harvest_detail with (security_invoker = true) as
select h.harvest_id, h.harvest_date, h.quantity_kg, h.selling_price_per_kg,
       round(h.quantity_kg * h.selling_price_per_kg, 2) as estimated_value,
       g.grade_name, r.remark_description,
       p.planting_id, p.planting_date, c.crop_name, c.variety,
       f.farm_id, f.farm_name, fr.farmer_id, fr.first_name || ' ' || fr.last_name as farmer_name
from harvest h
join quality_grade g on g.grade_id = h.grade_id
join harvest_remark r on r.remark_id = h.remark_id
join planting p on p.planting_id = h.planting_id
join crop c on c.crop_id = p.crop_id
join farm f on f.farm_id = p.farm_id
join farmer fr on fr.farmer_id = f.farmer_id;
